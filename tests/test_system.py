import os
import sys
from pathlib import Path

# Add project root to sys.path
BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from app.core.config import DB_PATH, REPORTS_DIR
from app.core.database import init_database, DatabaseManager
from app.capture.simulation_engine import SimulationEngine
from app.analysis.metrics import SpectrumAnalyzer, calculate_spectral_overlap_24
from app.analysis.optimizer import SpectrumOptimizer
from app.reports.pdf_generator import PDFReportGenerator
from app.reports.excel_exporter import ExcelReportExporter

def run_tests():
    print("=" * 60)
    print(" [TEST 1] Inicializando Base de Datos SQLite...")
    init_database()
    assert DB_PATH.exists(), f"Database file {DB_PATH} was not created!"
    print(f" [OK] Base de datos creada exitosamente en: {DB_PATH}")

    print("\n [TEST 2] Probando Motor de Captura Simulado...")
    engine = SimulationEngine()
    samples = engine.scan_once()
    assert len(samples) > 0, "No samples generated by SimulationEngine"
    print(f" [OK] Captura exitosa: {len(samples)} puntos de acceso detectados.")

    print("\n [TEST 3] Verificando Persistencia en SQLite...")
    session_id = DatabaseManager.create_session(
        name="Prueba de Validación de Sistema",
        location="Lab UNA Puno",
        engine_type="simulation",
        notes="Test suite automatizado"
    )
    assert session_id > 0, "Failed to create session"
    raw_samples = [s.to_dict() for s in samples]
    DatabaseManager.record_samples(session_id, raw_samples)
    saved_samples = DatabaseManager.get_session_samples(session_id)
    assert len(saved_samples) == len(samples), f"Expected {len(samples)} samples in DB, got {len(saved_samples)}"
    print(f" [OK] Sesión #{session_id} guardada con {len(saved_samples)} muestras en SQLite.")

    print("\n [TEST 4] Validando Algoritmos de Métricas y Solapamiento Espectral...")
    # Overlap tests
    assert calculate_spectral_overlap_24(1, 1) == 1.0, "Same channel overlap should be 1.0"
    assert calculate_spectral_overlap_24(1, 6) == 0.0, "Channels 1 and 6 should not overlap"
    overlap_1_2 = calculate_spectral_overlap_24(1, 2)
    assert 0 < overlap_1_2 < 1.0, f"Channels 1 and 2 should have partial overlap, got {overlap_1_2}"
    print(f" [OK] Solapamiento Ch 1 vs Ch 2: {overlap_1_2:.2f} (ACI detectada correctamente)")

    metrics = SpectrumAnalyzer.compute_channel_metrics(samples)
    assert "channels_24ghz" in metrics
    assert "channels_5ghz" in metrics
    print(f" [OK] Salud global del espectro calculada: {metrics['overall_health_score']}/100")

    print("\n [TEST 5] Probando Optimizador de Canales...")
    recs = SpectrumOptimizer.generate_recommendations(metrics)
    assert "optimal_channel_24" in recs
    assert "optimal_channel_5" in recs
    print(f" [OK] Canal óptimo recomendado 2.4 GHz: Canal {recs['optimal_channel_24']}")
    print(f" [OK] Canal óptimo recomendado 5 GHz: Canal {recs['optimal_channel_5']}")
    print(f" [OK] Hallazgos críticos detectados: {len(recs['findings'])}")

    print("\n [TEST 6] Generando Reporte PDF de Ingeniería...")
    sess = DatabaseManager.get_session(session_id)
    pdf_path = PDFReportGenerator.generate(
        session_data=sess,
        analysis=metrics,
        recommendations=recs,
        ap_list=raw_samples
    )
    assert pdf_path.exists(), "PDF report was not generated!"
    print(f" [OK] Reporte PDF creado exitosamente ({pdf_path.stat().st_size} bytes): {pdf_path.name}")

    print("\n [TEST 7] Generando Exportación Excel (.xlsx)...")
    excel_path = ExcelReportExporter.export(
        session_data=sess,
        analysis=metrics,
        recommendations=recs,
        ap_list=raw_samples
    )
    assert excel_path.exists(), "Excel report was not generated!"
    print(f" [OK] Reporte Excel creado exitosamente ({excel_path.stat().st_size} bytes): {excel_path.name}")

    DatabaseManager.end_session(session_id)
    print("\n" + "=" * 60)
    print(" [*] ¡TODOS LOS TESTS COMPLETADOS SATISFACTORIAMENTE! [*]")
    print("=" * 60)

if __name__ == "__main__":
    run_tests()
